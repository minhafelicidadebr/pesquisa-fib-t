import { supabase } from "@/integrations/supabase/client";
import type { Database } from "@/integrations/supabase/types";

export type CopsoqVersion = Database["public"]["Enums"]["copsoq_version"];
export type AppRole = Database["public"]["Enums"]["app_role"];
export type Company = Database["public"]["Tables"]["companies"]["Row"];
export type CompanyMember = Database["public"]["Tables"]["company_members"]["Row"];

export interface CreateCompanyInput {
  legal_name: string;
  cnpj?: string | null;
  sector?: string | null;
  estimated_employees?: number | null;
  sectors?: string[];
  copsoq_version?: CopsoqVersion;
}

/** Create a company owned by current user. Invite code auto-generated by trigger. */
export async function createCompany(input: CreateCompanyInput): Promise<Company> {
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) throw new Error("Sessão expirada. Entre novamente.");
  const { data, error } = await supabase
    .from("companies")
    .insert({
      owner_id: user.id,
      invite_code: "", // trigger overrides
      legal_name: input.legal_name,
      cnpj: input.cnpj ?? null,
      sector: input.sector ?? null,
      estimated_employees: input.estimated_employees ?? 0,
      sectors: input.sectors ?? [],
      copsoq_version: input.copsoq_version ?? "curto",
    })
    .select()
    .single();
  if (error) throw error;

  // Make owner an SST member of their own company
  await supabase.from("company_members").insert({
    company_id: data.id,
    user_id: user.id,
    role: "sst",
    sector: input.sector ?? null,
  });
  // Reflect role on user_roles for app-wide checks
  await supabase.from("user_roles").insert({ user_id: user.id, role: "sst" });

  return data as Company;
}

/** Join existing company via invite code (RPC). Returns company id. */
export async function joinCompanyByCode(
  code: string,
  sector: string | null,
  role: Extract<AppRole, "gestor" | "colaborador">,
): Promise<string> {
  const { data, error } = await supabase.rpc("join_company_by_code", {
    _code: code,
    _sector: sector,
    _role: role,
  });
  if (error) throw error;
  return data as string;
}

/** Fetch first company current user owns or is member of. */
export async function getMyCompany(): Promise<{ company: Company; role: AppRole | null } | null> {
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return null;

  const { data: owned } = await supabase
    .from("companies")
    .select("*")
    .eq("owner_id", user.id)
    .maybeSingle();
  if (owned) return { company: owned as Company, role: "sst" };

  const { data: member } = await supabase
    .from("company_members")
    .select("role, company_id, companies:companies(*)")
    .eq("user_id", user.id)
    .maybeSingle();
  if (member?.companies) {
    return {
      company: (member.companies as unknown) as Company,
      role: (member.role as AppRole) ?? null,
    };
  }
  return null;
}

export async function updateCompany(id: string, patch: Partial<CreateCompanyInput>): Promise<void> {
  const { error } = await supabase.from("companies").update(patch).eq("id", id);
  if (error) throw error;
}
